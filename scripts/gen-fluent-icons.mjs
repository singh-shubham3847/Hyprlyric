// Extracts only the Fluent UI System Icons (MIT) that word-map.ts references into a small
// generated module, so the app never ships the full 20k-icon set.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const mapFile = join(root, 'src/renderer/src/stage/icons/word-map.ts')
const outFile = join(root, 'src/renderer/src/stage/icons/fluent.gen.ts')
const set = JSON.parse(readFileSync(join(root, 'node_modules/@iconify-json/fluent/icons.json'), 'utf8'))

const names = [...new Set([...readFileSync(mapFile, 'utf8').matchAll(/'f:([a-z0-9-]+)'/g)].map((m) => m[1]))].sort()

function lookup(name) {
  let current = name
  for (let hops = 0; hops < 6; hops++) {
    if (set.icons[current]) return set.icons[current]
    const alias = set.aliases?.[current]
    if (!alias) return null
    current = alias.parent
  }
  return null
}

const VARIANTS = ['-24-filled', '-24-regular', '-20-filled', '-28-filled', '-32-filled', '-16-filled']
const out = {}
const missing = []
for (const base of names) {
  const icon = VARIANTS.map((v) => lookup(base + v)).find(Boolean)
  if (!icon) {
    missing.push(base)
    continue
  }
  out[base] = { body: icon.body, size: icon.width ?? set.width ?? 24 }
}

if (missing.length) {
  console.error(`Missing Fluent icons: ${missing.join(', ')}`)
  process.exit(1)
}

writeFileSync(
  outFile,
  `// Generated by scripts/gen-fluent-icons.mjs from @iconify-json/fluent (Fluent UI System Icons, MIT). Do not edit.\n` +
    `export const FLUENT_ICONS: Record<string, { body: string; size: number }> = ${JSON.stringify(out, null, 1)}\n`
)
console.log(`wrote ${Object.keys(out).length} Fluent icons to ${outFile}`)
